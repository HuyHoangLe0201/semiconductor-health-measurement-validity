def nominal(T,slopes=1.):
    T=np.asarray(T).reshape(-1)
    if T.min()<25-1e-9 or T.max()>175+1e-9:raise ValueError('Outside declared datasheet temperature domain')
    anchor=np.where(TR,np.interp(T,[25,125,175],[1.65,1.85,1.95]),np.interp(T,[25,125,175],[1.45,1.40,1.40]))
    r=R0*slopes
    return anchor-np.where(TR,40,20)*r,r

