def controller_py(t,sense,old):
    cand=p.STATES[np.all(abs(p.STATES-old)<=1,axis=1)]
    v,r=nominal(np.full(24,25));ids=p.path_ids(cand,sense,'Ttype')
    drop=np.sign(sense)*(A@v[:8])[ids]+sense*(A@r[:8])[ids]
    pred=sense+.025*((150*cand-drop-p.emf(t,p.CFG))@p.P0-.25*sense)
    cost=np.sum((pred-p.reference(t+50e-6))**2,axis=1)+.005*np.sum((cand-old)**2,axis=1)
    return cand[np.argmin(cost)]

def run(dll,N,case,aged,seed=20261012,replay=None,refine=4,native=True):
    rng=np.random.default_rng(seed);noise=rng.normal(0,case.get('noise',0),(N+1,3))
    states=np.zeros((N,3),np.int32);curr=np.zeros((N+1,3));sensed=curr.copy()
    thermal=np.zeros((N+1,24));thermal[0]=case['Tcase'];old=np.zeros(3,np.int32)
    state=np.zeros(99);capture=np.zeros(3);history=np.zeros((N+1,3))
    dv=np.zeros(24);dr=dv.copy()
    if aged:dv[0]=.05;dr[0]=.0002
    offset=np.array(case.get('skew_us',[0,0,0]))*1e-6
    delay=case.get('actuation_us',0)*1e-6;controller_mismatch=0
    def deriv(t,x,q):
        i=x[:3];T=case['Tcase']+x[3:].reshape(24,4).sum(axis=1)
        v,r=nominal(T,case.get('slope_factor',1.));v+=dv;r+=dr
        active=A[p.path_ids(q,i,'Ttype')]
        drop=(active*(v.reshape(3,8)+abs(i[:,None])*r.reshape(3,8))).sum(axis=1)
        pole=150*q-np.sign(i)*drop
        di=(p.P0@(pole-p.emf(t,p.CFG))-.25*i)/.002
        power=(active*(abs(i[:,None])*v.reshape(3,8)+i[:,None]**2*r.reshape(3,8))).ravel()
        modal=x[3:].reshape(24,4)
        return np.r_[di,((R*power[:,None]-modal)/TAU).ravel()]
    def step(t,x,q,h,depth=0):
        k1=deriv(t,x,q);s2=x+h*k1/2;k2=deriv(t+h/2,s2,q)
        s3=x+h*k2/2;k3=deriv(t+h/2,s3,q);s4=x+h*k3;k4=deriv(t+h,s4,q)
        end=x+h*(k1+2*k2+2*k3+k4)/6
        sign=np.sign(np.stack([x[:3],s2[:3],s3[:3],s4[:3],end[:3]]))
        if depth<8 and np.any(sign.min(axis=0)!=sign.max(axis=0)):
            return step(t+h/2,step(t,x,q,h/2,depth+1),q,h/2,depth+1)
        return end
    start=time.perf_counter()
    for k in range(N):
        sense=capture+noise[k]
        bits=case.get('bits',0)
        if bits:
            lsb=64/2**bits;sense=np.clip(np.rint(sense/lsb),-2**(bits-1),2**(bits-1)-1)*lsb
        sensed[k]=sense;history[k]=sense
        control=history[max(0,k-case.get('input_delay',0))]
        q=np.zeros(3,np.int32)
        if replay is None:
            dll.sil_control(k*50e-6,dp(control),ip(old),ip(q))
            if case['name']=='clean25':controller_mismatch+=int(np.any(q!=controller_py(k*50e-6,control,old)))
        else:q[:]=replay[k]
        states[k]=q
        free=np.where(state[:3]>=0,np.minimum(old,q),np.maximum(old,q))
        boundaries=[(old,delay),(free,1e-6),(q,49e-6-delay)];elapsed=0
        capture=state[:3].copy()
        sample_at=50e-6-offset
        for lev,duration in boundaries:
            if duration<=0:continue
            checkpoints=np.unique(np.r_[elapsed+np.linspace(0,duration,refine+1)[1:],sample_at[(sample_at>elapsed+1e-15)&(sample_at<=elapsed+duration+1e-15)]])
            for checkpoint in checkpoints:
                h=checkpoint-elapsed
                if h>1e-15:
                    if native:dll.sil_advance(k*50e-6+elapsed,dp(state),ip(lev),h,case['Tcase'],int(aged),case.get('slope_factor',1.))
                    else:state=step(k*50e-6+elapsed,state,lev,h)
                elapsed=checkpoint
                for j in range(3):
                    if abs(checkpoint-sample_at[j])<1e-14:capture[j]=state[j]
        curr[k+1]=state[:3];thermal[k+1]=case['Tcase']+state[3:].reshape(24,4).sum(axis=1)
        old=q.copy()
    sense=capture+noise[-1]
    if case.get('bits',0):
        lsb=64/2**case['bits'];sense=np.clip(np.rint(sense/lsb),-2**(case['bits']-1),2**(case['bits']-1)-1)*lsb
    sensed[-1]=sense
    assert np.max(abs(curr))<31.99,'ADC range violated'
    return dict(current=curr,sensed=sensed,states=states,junction=thermal,case=case,aged=aged,N=N,controller_mismatches=controller_mismatch,elapsed_s=time.perf_counter()-start)

def analyze(dll,rec,compensate=True,known_delay=None,temperature_offset=0.):
    N=rec['N'];X=np.zeros((N,2,50));y=np.zeros((N,2));keep=np.zeros(N,np.int32)
    old=np.vstack([np.zeros(3,np.int32),rec['states'][:-1]])
    for k in range(N):
        T=(rec['junction'][k]+rec['junction'][k+1])/2 if compensate else np.full(24,25)
        if compensate:T=T+temperature_offset
        v,r=nominal(T)
        keep[k]=dll.sil_observe(k*50e-6,dp(rec['sensed'][k]),dp(rec['sensed'][k+1]),ip(rec['states'][k]),ip(old[k]),dp(v),dp(r),known_delay or 0.,dp(X[k]),dp(y[k]))
    target=np.zeros(2);diag=np.zeros(4);start=time.perf_counter()
    status=dll.sil_fit(N,dp(X),dp(y),ip(keep),dp(target),dp(diag));elapsed=time.perf_counter()-start
    assert status==0,(status,diag)
    estimate,se,rank,defect,_,details=p.fit(X.reshape(-1,50),y.ravel(),keep=keep.astype(bool))
    difference=abs(target-estimate);assert difference.max()<1e-8,(difference,target,estimate)
    assert rank==36 and defect.max()<1e-7
    return dict(estimate=target.tolist(),nominal_SE=se.tolist(),rank=rank,retained=int(diag[0]),C_python_difference=difference.tolist(),target_defect=defect.tolist(),fit_elapsed_s=elapsed,QR_min_scaled_diagonal=float(diag[2])),(X,y,keep)

def operator_check(dll,rec):
    N=rec['N'];current=rec['sensed'];mid=(current[:-1]+current[1:])/2;q=rec['states']
    old=np.vstack([np.zeros(3,np.int32),q[:-1]]);free=np.where(mid>=0,np.minimum(old,q),np.maximum(old,q))
    Bleg=.04*A[p.path_ids(old,mid,'Ttype')]+.02*A[p.path_ids(free,mid,'Ttype')]+.94*A[p.path_ids(q,mid,'Ttype')]
    B=np.zeros((N,3,24))
    for phase in range(3):B[:,phase,8*phase:8*(phase+1)]=Bleg[:,phase]
    z=np.sign(mid);n=abs(q-free);T=(rec['junction'][:-1]+rec['junction'][1:])/2
    v=np.stack([nominal(temp)[0] for temp in T]).reshape(N,3,8);r=np.tile(R0,(N,1)).reshape(N,3,8)
    nominal_pole=150*(.04*old+.02*free+.94*q)-z*np.sum(Bleg*v,axis=2)-mid*np.sum(Bleg*r,axis=2)
    emf=20*np.sin(2*np.pi*25*(np.arange(N)[:,None]+.5)*50e-6+p.SHIFT)
    yp=(40*np.diff(current,axis=0)-nominal_pole+.25*mid+emf)@p.C.T
    xp=np.concatenate([-np.einsum('ab,kb,kbd->kad',p.C,z,B),-np.einsum('ab,kb,kbd->kad',p.C,mid,B),np.stack([-(n*z)@p.C.T,-mid@p.C.T],axis=2)],axis=2)
    keep=np.all((abs(current[:-1])>.5)&(abs(current[1:])>.5)&(current[:-1]*current[1:]>0),axis=1)
    xc=np.zeros_like(xp);yc=np.zeros_like(yp);kc=np.zeros(N,np.int32)
    for k in range(N):
        vv,rr=nominal(T[k]);kc[k]=dll.sil_observe(k*50e-6,dp(current[k]),dp(current[k+1]),ip(q[k]),ip(old[k]),dp(vv),dp(rr),2e-6,dp(xc[k]),dp(yc[k]))
    np.testing.assert_array_equal(kc.astype(bool),keep)
    dx=float(abs(xc[keep]-xp[keep]).max());dy=float(abs(yc[keep]-yp[keep]).max());assert dx<1e-12 and dy<1e-11,(dx,dy)
    target=np.zeros(2);diag=np.zeros(4);short_status=dll.sil_fit(N,dp(xc),dp(yc),ip(kc),dp(target),dp(diag))
    assert short_status<0,'A short physical window with missing sign/path support must be rejected'
    return dict(operator_X_difference=dx,operator_y_difference=dy,operator_retention_match=True,short_physical_window_status=short_status,short_physical_window_periods=N)

def check(dll):
    rng=np.random.default_rng(20261013);mismatch=0
    for k in range(2000):
        sense=rng.uniform(-25,25,3);old=p.STATES[rng.integers(27)].astype(np.int32);q=np.zeros(3,np.int32);t=rng.uniform(0,1)
        dll.sil_control(t,dp(sense),ip(old),ip(q));mismatch+=int(np.any(q!=controller_py(t,sense,old)))
    assert mismatch==0
    fixture=dict(name='plant_parity',Tcase=75,actuation_us=2,skew_us=[0,1,2])
    cpp=run(dll,128,fixture,True);py=run(dll,128,fixture,True,replay=cpp['states'],native=False)
    parity_i=float(abs(cpp['current']-py['current']).max());parity_T=float(abs(cpp['junction']-py['junction']).max())
    # Zero-current commutation branches are sensitive to roundoff in P0 versus
    # explicit neutral elimination; require agreement well below sensor noise.
    assert parity_i<1e-6 and parity_T<1e-6,(parity_i,parity_T)
    operator=operator_check(dll,cpp)
    # Independent analytic Foster step response, not the trajectory integrator.
    t=np.geomspace(1e-6,1,300);z=(R[:,:,None]*(1-np.exp(-t/TAU[:,:,None]))).sum(axis=1)
    assert np.all(np.diff(z,axis=1)>=0);np.testing.assert_allclose(R.sum(axis=1),np.where(TR,.6,1.8),atol=1e-12)
    v,r=nominal(np.full(24,25));np.testing.assert_allclose((v+np.where(TR,40,20)*r)[[0,1]],[1.65,1.45],atol=1e-14)
    # A nonseparating record must be rejected rather than assigned a health vector.
    X=np.zeros((50,2,50));y=np.zeros((50,2));keep=np.ones(50,np.int32);out=np.zeros(2);diag=np.zeros(4)
    status=dll.sil_fit(50,dp(X),dp(y),ip(keep),dp(out),dp(diag));assert status<0
    return dict(controller_random_vectors=2000,controller_mismatches=mismatch,nonseparating_status=status,thermal_Rsum_verified=True,static_anchors_verified=True,independent_plant_C_Python_current_difference_A=parity_i,independent_plant_C_Python_temperature_difference_K=parity_T,**operator)

